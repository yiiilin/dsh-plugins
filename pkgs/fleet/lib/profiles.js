/**
 * Dynamic profile materialization for fleet boxes.
 *
 * A box is not a hand-maintained profile: the fleet host writes one on demand.
 * The generated profile is a normal `dsh` profile directory under
 * `$DSH_HOME/profiles/<name>/`, so `dsh --profile <name>` works on it directly
 * and an operator can inspect or repair it with the usual tooling.
 *
 * Two shapes exist:
 *
 * - **local** — the shipped `web` bundle composition, unchanged. The box runs
 *   with the host filesystem and processes, exactly like the fleet host's own
 *   `dsh web`.
 * - **ssh** — the same composition with the filesystem, subprocess and sandbox
 *   providers replaced by their SSH counterparts. The three providers live on
 *   the **host** plane, so the Web file browser, AGENTS.md loading, git, the
 *   session cwd and the terminal all observe the remote machine; a preset realm
 *   could not do that, because those consumers are host rows that never see a
 *   preset's realm.
 *
 * @module @yiln-dsh/dsh-fleet/profiles
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

/**
 * Bundles a generated profile starts from.
 *
 * These are the shipped web composition's bundles, not a reference to any
 * particular deployment's web plugin. A host that has swapped its web bundle
 * passes its own list through the `profileBundles` config, so this module never
 * has to know which web plugin is installed.
 */
export const DEFAULT_PROFILE_BUNDLES = ['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-web-app']

/**
 * Bundle layers a box profile mounts by default.
 *
 * A box that carries only `dsh-base` + `dsh-web-app` is a bare harness: no
 * deployment preset, no deployment tuning. Including the agent-preset bundle
 * gives the box the same preset roster the fleet host has, which is what makes
 * a box feel like "the same development environment on another machine".
 *
 * The deployment's own plugin packages are deliberately *not* here: several of
 * them (the authenticated gateway, the daemon manager) own host-wide resources a
 * box must not duplicate.
 */
export const DEFAULT_BOX_BUNDLES = [
  '@deepseek-ai/dsh-base',
  '@deepseek-ai/dsh-web-app',
  '@local/yiln-agent-preset',
]

/**
 * Harness modules a box profile must install explicitly.
 *
 * They exist in the dsh install tree but not in the profile's node_modules, so a
 * preset that mounts them breaks if dsh is ever installed in a trimmed or
 * self-contained form. Declaring them pins the box to resolvable packages.
 */
export const BOX_HARNESS_MODULES = [
  'dsh-tool-schedule',
  'dsh-plugin-manager',
  'dsh-workflow-ptc',
  'dsh-tool-terminal',
  'dsh-experimental-worktree',
  'dsh-experimental-tool-worktree',
]

/**
 * Dependencies a box profile declares for its bundle layers.
 *
 * @param bundles - the box's bundle layers.
 * @param options.agentPresetsDir - `$DSH_HOME/.agent-presets`, when one exists.
 * @param options.harnessVersion - version to pin the harness modules to.
 * @returns the dependency map written into the box manifest.
 */
export function boxDependencies(bundles, { agentPresetsDir, harnessVersion }) {
  const dependencies = {}
  if (agentPresetsDir !== undefined && bundles.includes('@local/yiln-agent-preset')) {
    // A link keeps the box on the deployment's live preset rather than a copy.
    dependencies['@local/yiln-agent-preset'] = `link:${join(agentPresetsDir, 'yiln', 'bundle')}`
  }
  if (harnessVersion !== undefined) {
    for (const module of BOX_HARNESS_MODULES) {
      dependencies[`@deepseek-ai/${module}`] = harnessVersion
    }
  }
  return dependencies
}

/** The provider packages an SSH box profile depends on. */
export const SSH_PROVIDER_PACKAGES = [
  '@deepseek-ai/dsh-ssh',
  '@deepseek-ai/dsh-fs-ssh',
  '@deepseek-ai/dsh-subprocess-ssh',
  '@deepseek-ai/dsh-sandbox-ssh',
]

/** Header shared by every generated patch file. */
const PATCH_HEADER = `# Generated by @yiln-dsh/dsh-fleet — edits here are overwritten.
# Change the box through the fleet settings instead of editing this file.
`

/**
 * Render the SSH provider layer for one box.
 *
 * The local provider rows cannot be *renamed* in place: the Loader asserts the
 * existing plugin name for an id-targeted patch and skips a mismatch with a
 * warning, which silently leaves the local provider mounted. Each row is
 * therefore disabled and its SSH counterpart inserted under a new id.
 *
 * @param box - a normalized SSH box.
 * @returns YAML patch text.
 */
export function renderSshPatch(box) {
  return `${PATCH_HEADER}
- insert:
    - id: ssh
      name: '@deepseek-ai/dsh-ssh'
      config:
        host: ${yamlString(box.sshHost)}
        launch:
          kind: node-script
          node: ${yamlString(box.sshNode)}
        helper: ${yamlString(box.sshHelper)}
        helperHash: ${yamlString(box.sshHelperHash)}
        workspace: ${yamlString(box.workspace)}

# --- filesystem: disable the local sandboxed provider, insert the remote one ---
- id: fs-sandbox
  disabled: true
- insert:
    - id: fs-ssh
      name: '@deepseek-ai/dsh-fs-ssh'

# --- subprocess and terminal ---
- id: subprocess
  disabled: true
- insert:
    - id: subprocess-ssh
      name: '@deepseek-ai/dsh-subprocess-ssh'

# --- sandbox ---
- id: sandbox
  disabled: true
- insert:
    - id: sandbox-ssh
      name: '@deepseek-ai/dsh-sandbox-ssh'

# The workspace root is canonicalized on the remote host by the helper.
- id: sandbox-policy
  config:
    mode: danger-full-access
    workspaceRoot: ${yamlString(box.workspace)}

# \`danger-full-access\` must pair with approval \`never\`. Permission presets
# compose a sandbox mode and an approval policy into one preset, so a box left
# on the shipped \`ask\` default matches no preset and the permission plugin
# refuses to activate ("composed sandbox and approval defaults match no preset").
# Verified against a running SSH box.
- id: approval
  config:
    policy: never
`
}


/**
 * Merge an operator fragment into a patch file's single YAML sequence.
 *
 * A patch file is one top-level sequence, so a fragment cannot be appended as
 * text: after an empty `[]` document, a following `- id:` line is a parse error.
 * The fragment's leading marker is dropped and its rows are inserted before the
 * end of the sequence.
 *
 * @param rows - the box's own patch text, ending with a top-level sequence.
 * @param fragment - the operator's YAML rows, or an empty string.
 * @returns the merged patch text without a trailing newline.
 */
export function mergeFragment(rows, fragment) {
  const extra = fragment.trim()
  if (extra === '') return rows.trimEnd()
  const body = rows.trimEnd()
  // An empty sequence carries no content of its own to keep.
  if (body.endsWith('[]')) {
    const head = body.slice(0, -2).trimEnd()
    return `${head}${head === '' ? '' : '\n'}\n${extra}`
  }
  return `${body}\n${extra}`
}

/**
 * Render the patch layer for a local box.
 *
 * @returns YAML patch text with no overrides.
 */
export function renderLocalPatch() {
  return `${PATCH_HEADER}[]\n`
}

/**
 * Materialize one profile directory.
 *
 * Existing files are updated rather than replaced wholesale, so a profile that
 * already carries operator tuning keeps it.
 *
 * @param profileDir - absolute profile directory to create.
 * @param box - the box the profile serves.
 * @param bundles - bundle layers for the generated profile.
 * @returns the written paths.
 */
export async function writeProfile(
  profileDir,
  box,
  bundles = DEFAULT_PROFILE_BUNDLES,
  dependencies = {},
  extraPatch = '',
) {
  await mkdir(profileDir, { recursive: true })
  const packagePath = join(profileDir, 'package.json')
  const manifest = {
    name: `dsh-profile-${box.profile}`,
    private: true,
    dependencies,
    dsh: { profile: { bundles: [...bundles], patchReload: 'startup' } },
  }
  await writeFile(packagePath, `${JSON.stringify(manifest, null, 2)}\n`)
  // pnpm treats a directory without this as part of a parent workspace; a box
  // profile must install into its own tree.
  await writeFile(join(profileDir, 'pnpm-workspace.yaml'), 'packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n')
  // A profile root is an empty entry list; the tree is composed from bundles
  // and the patch layer beside it.
  await writeFile(join(profileDir, 'cordis.yml'), '[]\n')
  // A box carries no deployment knowledge of its own: whatever the operator
  // needs — model routing, preset defaults, local tuning — is merged in as an
  // opaque fragment, so this package never learns a deployment's providers.
  const rows = box.kind === 'ssh' ? renderSshPatch(box) : renderLocalPatch()
  await writeFile(
    join(profileDir, 'cordis.patch.yml'),
    `${mergeFragment(rows, extraPatch)}\n`,
  )
  return {
    packagePath,
    patchPath: join(profileDir, 'cordis.patch.yml'),
    rootPath: join(profileDir, 'cordis.yml'),
  }
}

/**
 * Read the profile a box would run, for display in the settings card.
 *
 * @param profileDir - the profile directory.
 * @returns the patch text, or undefined when the profile is absent.
 */
export async function readProfilePatch(profileDir) {
  try {
    return await readFile(join(profileDir, 'cordis.patch.yml'), 'utf8')
  } catch (error) {
    if (error.code === 'ENOENT') return undefined
    throw error
  }
}

/** Quote a value as a YAML double-quoted scalar. */
function yamlString(value) {
  return JSON.stringify(String(value))
}
