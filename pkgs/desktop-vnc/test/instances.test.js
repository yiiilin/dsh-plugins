/**
 * Unit tests for the browser instance table: the entries it holds, the ports it
 * reserves, the ownership reaper, and the viewer count the sidebar renders.
 *
 * Every test drives the table through its public surface with a fake backend, so
 * nothing here needs an X server, Xephyr or Chromium.
 */

import assert from 'node:assert/strict'
import test from 'node:test'

import { createInstanceRegistry } from '../instances.js'

/** A clock the test advances by hand. */
function fakeClock(startMs = 1_000_000) {
  const clock = { ms: startMs }
  clock.now = () => clock.ms
  clock.advance = (ms) => {
    clock.ms += ms
    return clock.ms
  }
  return clock
}

/** A backend that starts cleanly and records what happened to it. */
function fakeBackend({ display = ':200', port = 5900 } = {}) {
  const calls = { ensure: 0, dispose: 0 }
  const backend = {
    calls,
    browser: {
      ensure: async () => {
        calls.ensure += 1
        return { ok: true, display }
      },
      status: () => ({ display, running: true, xephyr: true, chromium: true, mode: 'xephyr', degraded: false, pids: {} }),
      stop: async () => {},
    },
    vnc: {
      ensure: async () => ({ running: true, port }),
      status: () => ({ running: true, port }),
      display: () => display,
      setDisplay: () => display,
      setAuthority: () => undefined,
      stop: async () => {},
    },
    capture: {
      setDisplay: () => display,
      setAuthority: () => undefined,
      capture: async () => Buffer.alloc(0),
    },
    dispose: async () => {
      calls.dispose += 1
    },
  }
  return backend
}

/** A registry wired to fake infrastructure, fast timings and a hand-driven clock. */
function makeRegistry({ ports = [5900, 5901, 5902], prepareDisplay, backend, clock = fakeClock() } = {}) {
  const backends = []
  const registry = createInstanceRegistry({
    createBackend: (context) => {
      // The real factory binds the port the table claimed for this instance, so
      // the fake does too: whatever ensure() reports must be that port.
      const created = backend === undefined
        ? fakeBackend({ display: ':200', port: context.port })
        : backend(backends.length)
      backends.push(created)
      return created
    },
    prepareDisplay: prepareDisplay ?? (async () => ({ display: ':200' })),
    ports,
    viewport: { width: 1280, height: 800 },
    now: clock.now,
    log: () => {},
  })
  return { registry, clock, backends }
}

test('create() answers with the new id and the starting state before the stack is up', async () => {
  let releaseDisplay
  const displayGate = new Promise((resolve) => {
    releaseDisplay = resolve
  })
  const { registry } = makeRegistry({
    prepareDisplay: async () => {
      await displayGate
      return { display: ':200' }
    },
  })

  const created = registry.create({ ownerSessionId: 'session-a' })

  // The whole contract of the create endpoint: exactly these two fields, and the
  // answer must not wait for a browser that is still coming up.
  assert.deepEqual(Object.keys(created).sort(), ['id', 'state'])
  assert.equal(created.state, 'starting')
  // Generated by this plugin, never taken from an external tool: short hex.
  assert.match(created.id, /^[0-9a-f]{8}$/)
  assert.equal(registry.list()[0].state, 'starting', 'the row reports starting while the stack boots')

  releaseDisplay()
  await registry.get(created.id).ready

  assert.equal(registry.list()[0].state, 'ready')
  assert.equal(registry.list().length, 1, 'settling the boot neither adds nor replaces rows')
})

test('the list row carries the owner, the size and both timestamps in epoch seconds', async () => {
  const clock = fakeClock(1_000_000)
  const { registry } = makeRegistry({ clock })
  const { id } = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(id).ready

  assert.deepEqual(registry.list(), [{
    id,
    state: 'ready',
    width: 1280,
    height: 800,
    createdAt: 1_000,
    ownerSessionId: 'session-a',
    lastActiveAt: 1_000,
    viewers: 0,
  }])
})

test('two create() calls get different ids and both appear in the list', async () => {
  const { registry } = makeRegistry()
  const first = registry.create({ ownerSessionId: 'session-a' })
  const second = registry.create({ ownerSessionId: 'session-a' })

  assert.notEqual(first.id, second.id)
  assert.deepEqual(registry.list().map((row) => row.id), [first.id, second.id])
  await Promise.all([registry.get(first.id).ready, registry.get(second.id).ready])
})

test('two instances created at once reserve different RFB ports', async () => {
  // The probe-then-bind handshake is not atomic, so the table has to hold the
  // claim: both boots ask for a port before either has bound one.
  const { registry } = makeRegistry({ ports: [5900, 5901] })
  const first = registry.create({ ownerSessionId: 'session-a' })
  const second = registry.create({ ownerSessionId: 'session-a' })
  await Promise.all([registry.get(first.id).ready, registry.get(second.id).ready])

  const ports = [registry.get(first.id).port, registry.get(second.id).port]
  assert.deepEqual(ports.slice().sort(), [5900, 5901])
  assert.equal(registry.list().length, 2)
})

test('the port of a closed instance is released for the next one', async () => {
  const { registry } = makeRegistry({ ports: [5900] })
  const first = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(first.id).ready
  assert.equal(registry.get(first.id).port, 5900)

  assert.deepEqual(await registry.close(first.id), { closed: true })
  assert.equal(registry.list().length, 0)

  const second = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(second.id).ready
  assert.equal(registry.get(second.id).port, 5900, 'the only port in the pool is free again')
})

test('a full port pool refuses the create instead of sharing a port', async () => {
  const { registry } = makeRegistry({ ports: [5900] })
  const first = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(first.id).ready

  // An exhausted pool is a create-time failure: the caller is told at once, with
  // the open instances named so it can close one and retry in one step.
  const error = (() => {
    try {
      registry.create({ ownerSessionId: 'session-a' })
      return null
    } catch (caught) {
      return caught
    }
  })()

  assert.ok(error !== null, 'create() must not silently share the one port')
  assert.equal(error.status, 503)
  assert.match(error.message, /RFB 端口/)
  assert.match(error.message, new RegExp(first.id))
  assert.equal(registry.get(first.id).state, 'ready', 'the existing instance is untouched')
  assert.equal(registry.list().length, 1)
})

test('closing an unknown instance is a clear error, not a silent success', async () => {
  const { registry } = makeRegistry()
  const error = await registry.close('deadbeef').catch((reason) => reason)
  assert.equal(error.status, 404)
  assert.match(error.message, /deadbeef/)
})

test('close() stops the stack it owns and reports closed', async () => {
  const { registry, backends } = makeRegistry()
  const { id } = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(id).ready

  assert.deepEqual(await registry.close(id), { closed: true })
  assert.equal(backends[0].calls.dispose, 1, 'the stack this instance started is disposed')
  assert.equal(registry.get(id), undefined)
})

test('a failed start is reported on the row with its reason', async () => {
  // The display seam is where a missing Xephyr surfaces: resolving the nested
  // display runs the browser stack's ensure(), and its failure is the error.
  const { registry } = makeRegistry({
    prepareDisplay: async () => ({ error: 'Xephyr 未安装（Xephyr not installed）' }),
  })
  const { id } = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(id).ready

  const row = registry.list()[0]
  assert.equal(row.state, 'failed')
  // The reason lives on the entry, not in the list row: the row keeps the frozen
  // shape, and the failure detail is read by whoever asks for this instance.
  assert.match(registry.get(id).error, /Xephyr 未安装/)
})

test('the RFB server is not started until somebody watches', async () => {
  // One x11vnc per idle browser would burn a process on every instance nobody
  // looks at, so `ready` means "the browser is up" and the RFB server starts when
  // a viewer connects.
  let vncEnsures = 0
  const { registry } = makeRegistry({
    backend: () => ({
      browser: { ensure: async () => ({ ok: true, display: ':200' }) },
      vnc: {
        ensure: async () => {
          vncEnsures += 1
          return { running: true, port: 5900 }
        },
      },
      capture: null,
      dispose: async () => {},
    }),
  })
  const { id } = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(id).ready

  assert.equal(registry.list()[0].state, 'ready')
  assert.equal(vncEnsures, 0, 'nothing is watching, so no RFB server was started')
})

// --- ownership: the session that created an instance reaps it ----------------

test('a disposed session closes its own instances and leaves the others alone', async () => {
  const { registry, backends } = makeRegistry({ ports: [5900, 5901, 5902] })
  const mine = registry.create({ ownerSessionId: 'session-a' })
  const mineToo = registry.create({ ownerSessionId: 'session-a' })
  const theirs = registry.create({ ownerSessionId: 'session-b' })
  await Promise.all([
    registry.get(mine.id).ready,
    registry.get(mineToo.id).ready,
    registry.get(theirs.id).ready,
  ])

  await registry.disposeSession('session-a')

  assert.deepEqual(registry.list().map((row) => row.id), [theirs.id], 'only the other session keeps its instance')
  assert.equal(registry.get(mine.id), undefined)
  assert.equal(registry.get(mineToo.id), undefined)
  assert.equal(registry.get(theirs.id).state, 'ready')
  // Exactly the two stacks of the disposed session were torn down.
  assert.deepEqual(backends.map((backend) => backend.calls.dispose), [1, 1, 0])
})

test('a session with no instances disposes nothing', async () => {
  const { registry, backends } = makeRegistry()
  const kept = registry.create({ ownerSessionId: 'session-b' })
  await registry.get(kept.id).ready

  await registry.disposeSession('session-a')

  assert.equal(registry.list().length, 1)
  assert.equal(backends[0].calls.dispose, 0)
})

test('an instance with no recorded owner is not swept up by an unrelated session', async () => {
  const { registry } = makeRegistry()
  const orphan = registry.create({})
  await registry.get(orphan.id).ready

  await registry.disposeSession('session-a')

  assert.equal(registry.list().length, 1, 'an unknown owner is not "every session"')
})

test('closing an instance is reported to the caller-supplied hook exactly once', async () => {
  const closed = []
  const registry = createInstanceRegistry({
    createBackend: (context) => fakeBackend({ display: context.display, port: context.port }),
    prepareDisplay: async () => ({ display: ':200' }),
    ports: [5900],
    viewport: { width: 1280, height: 800 },
    now: fakeClock().now,
    log: () => {},
    onClose: (id) => closed.push(id),
  })
  const first = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(first.id).ready

  await registry.close(first.id)
  // A second close finds nothing and must not fire the hook again.
  await registry.close(first.id).catch(() => {})

  assert.deepEqual(closed, [first.id])
})

// --- viewers: the count the sidebar shows ------------------------------------

test('attaching and detaching viewers is reflected in the row', async () => {
  const clock = fakeClock(1_000_000)
  const { registry } = makeRegistry({ clock })
  const { id } = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(id).ready

  registry.attachViewer(id)
  registry.attachViewer(id)
  assert.equal(registry.list()[0].viewers, 2, 'two clients on one instance is two viewers')

  clock.advance(5_000)
  registry.detachViewer(id)
  assert.equal(registry.list()[0].viewers, 1)
  assert.equal(registry.list()[0].lastActiveAt, 1_005, 'watching counts as activity')

  registry.detachViewer(id)
  // A stray detach must never make the count negative.
  registry.detachViewer(id)
  assert.equal(registry.list()[0].viewers, 0)
})

test('attaching a viewer to an unknown id changes nothing', () => {
  const { registry } = makeRegistry()
  assert.equal(registry.attachViewer('deadbeef'), undefined)
  assert.equal(registry.detachViewer('deadbeef'), undefined)
  assert.deepEqual(registry.list(), [])
})

test('closing an instance while it is still booting leaves no row and frees the port', async () => {
  let releaseDisplay
  const displayGate = new Promise((resolve) => {
    releaseDisplay = resolve
  })
  const { registry } = makeRegistry({
    ports: [5900],
    prepareDisplay: async () => {
      await displayGate
      return { display: ':200' }
    },
  })

  const { id } = registry.create({ ownerSessionId: 'session-a' })
  await registry.close(id)
  releaseDisplay()
  // Let the in-flight boot run to completion after the close.
  await new Promise((resolve) => setImmediate(resolve))

  assert.equal(registry.list().length, 0, 'a boot that finishes after a close must not resurrect the row')
  assert.equal(registry.claimedPorts.size, 0, 'and it must not keep the port claimed')
})

test('the port the RFB server reports is the one the bridge must connect to', async () => {
  // `status()` answers the *preferred* port before the first allocation, so a
  // bridge that read status() would connect to the wrong port once a pool is in
  // play. The allocated port comes from ensure()'s return value, which is what
  // the entry records.
  const { registry } = makeRegistry({ ports: [5900, 5901] })
  const { id } = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(id).ready

  const entry = registry.get(id)
  const started = await entry.vnc.ensure()

  assert.equal(started.port, entry.port, 'the entry holds the port the server actually bound')
})

test('two viewers on one instance count as two, and closing them counts down once each', async () => {
  const { registry } = makeRegistry()
  const { id } = registry.create({ ownerSessionId: 'session-a' })
  await registry.get(id).ready

  // The bridge calls these from both sockets' close handlers, so a double release
  // is the failure mode worth pinning: the count is what the sidebar renders.
  registry.attachViewer(id)
  registry.attachViewer(id)
  assert.equal(registry.list()[0].viewers, 2)

  registry.detachViewer(id)
  registry.detachViewer(id)
  assert.equal(registry.list()[0].viewers, 0)
})
