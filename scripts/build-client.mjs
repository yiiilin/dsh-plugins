import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import vm from 'node:vm'
import { FEATURES } from '../src/features.js'

const root = new URL('../', import.meta.url)
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'))
const factories = []
for (const feature of FEATURES.filter((entry) => entry.client)) {
  let entry
  const window = { __ModuleLoader__: { load(value) {
    assert.equal(entry, undefined, `Multiple registrations in ${feature.key}`)
    entry = value
  } } }
  const file = new URL(`src/${feature.key}/${feature.client}`, root)
  vm.runInNewContext(await readFile(file, 'utf8'), { window }, { filename: file.pathname, timeout: 1000 })
  assert.equal(typeof entry?.factory, 'function', `Missing client factory: ${feature.key}`)
  factories.push(`[${JSON.stringify(feature.key)}, ${entry.factory.toString()}]`)
}
const services = ['connection', 'slots', 'locale', 'sessions', 'timer', 'sidebarRight', 'sidebarRightTabs', 'remote', 'remote.session']
const source = `// Generated by scripts/build-client.mjs; edit src/<feature> client sources instead.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory: (require) => {\n    const factories = [\n${factories.join(',\n')}\n    ];\n    return {\n      name: 'yiln-dsh-plugins-client',\n      inject: ${JSON.stringify(services)},\n      async apply(ctx) {\n        ctx.effect(() => () => {\n          for (const style of document.querySelectorAll('style[data-plugin="${manifest.name}"]')) style.remove();\n        }, 'suite client styles');\n        const children = [];\n        for (const [key, factory] of factories) {\n          const feature = factory(require);\n          children.push(ctx.plugin({ ...feature, name: 'suite-' + key }));\n        }\n        await Promise.all(children);\n      },\n    };\n  },\n});\n`
new vm.Script(source)
await writeFile(new URL('client.js', root), source)
console.log(`Built one client entry with ${factories.length} feature factories`)
